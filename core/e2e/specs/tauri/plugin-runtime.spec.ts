import {expect, Page, test} from '@playwright/test';
import {AppHelper} from '../../support/app-helper';
import {
  MOCK_GENERATED_CONTENT,
  MOCK_PLUGIN_ELEMENT,
  MOCK_PLUGIN_MODEL,
  mockPlugin,
  mockPluginBackend,
  PluginBackendMock,
} from '../../support/plugin-mocks';
import {TauriHelper} from '../../support/tauri-helper';

const PLUGIN_MENU_ACTION = 'PLUGIN_MENU_ACTION';

const PLUGIN_ASPECT_URN = 'urn:samm:org.eclipse.examples.plugin:1.0.0#PluginAspect';

const hostDialog = (page: Page) => page.locator('mat-dialog-container').filter({has: page.getByTestId('plugin-host-dialog')});

test.describe('Plugin runtime', () => {
  let tauri: TauriHelper;
  let app: AppHelper;
  let backend: PluginBackendMock;

  const open = async (page: Page, plugins = [mockPlugin()]) => {
    tauri = new TauriHelper(page);
    await tauri.initTauriMock();
    backend = await mockPluginBackend(page, plugins);
    app = new AppHelper(page);
    await app.visitDefault();
  };

  const openWithModel = async (page: Page) => {
    await open(page);
    await app.loadModel(MOCK_PLUGIN_MODEL);
    await expect(app.getHTMLCell('PluginAspect')).toBeVisible({timeout: 20000});
  };

  const expectGeneratedFile = async (page: Page) => {
    await page.getByTestId('e2e-plugin-run').click();
    expect((await tauri.savedFile('model.e2e.txt')).text).toBe(MOCK_GENERATED_CONTENT);
    await expect(hostDialog(page)).toHaveCount(0);
    await expect(page.locator('.toast-success')).toContainText('Generated by plugin');
    const generation = backend.requests.find(request => request.method === 'POST' && request.path === '/e2e-import/generators/e2e');
    expect(generation).toBeDefined();
  };

  test('publishes the menu entries of running plugins', async ({page}) => {
    await open(page, [mockPlugin(), mockPlugin({id: 'broken', state: 'FAILED'})]);

    await expect
      .poll(async () => (await tauri.getSentEvents('setPluginMenu')).at(-1)?.args[0])
      .toEqual({
        title: 'Plugins',
        entries: [
          {pluginId: 'e2e-import', entryId: 'import', label: 'Import from E2E...', location: 'file/import', enabled: true},
          {pluginId: 'e2e-import', entryId: 'export', label: 'Export to E2E...', location: 'generate', enabled: false},
        ],
      });
  });

  test('enables generator menu entries once an Aspect Model is open', async ({page}) => {
    await openWithModel(page);

    await expect
      .poll(async () =>
        (await tauri.getSentEvents('setPluginMenu')).at(-1)?.args[0].entries.map((entry: {enabled: boolean}) => entry.enabled),
      )
      .toEqual([true, true]);
  });

  test('opens the plugin for its menu entry and imports a model with it', async ({page}) => {
    await open(page);
    await expect.poll(async () => (await tauri.getSentEvents('setPluginMenu')).length).toBeGreaterThan(0);

    await tauri.emitSignal(PLUGIN_MENU_ACTION, {pluginId: 'e2e-import', entryId: 'import'});

    await expect(hostDialog(page)).toBeVisible();
    await expect(page.getByTestId('plugin-host-title')).toHaveText('Import from E2E...');
    await expect(page.locator(MOCK_PLUGIN_ELEMENT)).toBeVisible();
    await expect(page.getByTestId('e2e-plugin-info')).toHaveText('1|e2e-import|import|import|en|-|-');

    await page.getByTestId('e2e-plugin-run').click();

    await expect(hostDialog(page)).toHaveCount(0);
    await expect(app.getHTMLCell('PluginAspect')).toBeVisible({timeout: 20000});
    await expect(page.locator('.toast-success')).toContainText('Imported by plugin');
  });

  test('closes the plugin with the close button of the dialog', async ({page}) => {
    await open(page);
    await expect.poll(async () => (await tauri.getSentEvents('setPluginMenu')).length).toBeGreaterThan(0);

    await tauri.emitSignal(PLUGIN_MENU_ACTION, {pluginId: 'e2e-import', entryId: 'import'});
    await expect(page.locator(MOCK_PLUGIN_ELEMENT)).toBeVisible();
    await page.getByTestId('plugin-host-close').click();

    await expect(hostDialog(page)).toHaveCount(0);
  });

  test('warns about entries of plugins which are not running', async ({page}) => {
    await open(page, [mockPlugin({state: 'FAILED'})]);
    await expect.poll(async () => (await tauri.getSentEvents('setPluginMenu')).length).toBeGreaterThan(0);

    await tauri.emitSignal(PLUGIN_MENU_ACTION, {pluginId: 'e2e-import', entryId: 'import'});

    await expect(page.locator('.toast-warning')).toContainText('The plugin "E2E Import" is not running');
    await expect(hostDialog(page)).toHaveCount(0);
  });

  test('runs generator commands from the toolbar with the open model', async ({page}) => {
    await openWithModel(page);

    await page.getByTestId('tbPluginsButton').click();
    await expect(page.getByTestId('tbPluginCommand-e2e-import-import')).toHaveCount(0);
    await page.getByTestId('tbPluginCommand-e2e-import-export').click();

    await expect(page.getByTestId('plugin-host-title')).toHaveText('Export to E2E...');
    await expect(page.getByTestId('e2e-plugin-info')).toHaveText(
      '1|e2e-import|export|generate|en|org.eclipse.examples.plugin:1.0.0/PluginAspect.ttl|-',
    );
    await expectGeneratedFile(page);
  });

  test('gives generators the selected element', async ({page}) => {
    await openWithModel(page);

    await app.clickShape('PluginAspect');
    await page.getByTestId('tbPluginsButton').click();
    await page.getByTestId('tbPluginCommand-e2e-import-export').click();

    await expect(page.getByTestId('e2e-plugin-info')).toHaveText(
      `1|e2e-import|export|generate|en|org.eclipse.examples.plugin:1.0.0/PluginAspect.ttl|${PLUGIN_ASPECT_URN}`,
    );
    await expectGeneratedFile(page);
  });

  test('shows no plugin commands in the toolbar without running plugins', async ({page}) => {
    await open(page, [mockPlugin({state: 'FAILED'})]);
    await expect.poll(async () => (await tauri.getSentEvents('setPluginMenu')).length).toBeGreaterThan(0);

    await expect(page.getByTestId('tbPluginsButton')).toHaveCount(0);
  });
});
