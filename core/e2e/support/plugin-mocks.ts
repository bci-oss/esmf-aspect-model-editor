import {Page, Route} from '@playwright/test';

/** Custom element used as user interface of the mocked plugin; it exercises the host API like a real plugin. */
export const MOCK_PLUGIN_ELEMENT = 'ame-plugin-e2e-import';

export const MOCK_PLUGIN_MODEL = `@prefix samm: <urn:samm:org.eclipse.esmf.samm:meta-model:2.2.0#> .
@prefix : <urn:samm:org.eclipse.examples.plugin:1.0.0#> .

:PluginAspect a samm:Aspect ;
   samm:properties ( ) ;
   samm:operations ( ) .
`;

const MOCK_PLUGIN_MODULE = `
class E2eElement extends HTMLElement {
  connectedCallback() {
    const host = this.host;
    this.innerHTML = '<p data-testid="e2e-plugin-info"></p><button data-testid="e2e-plugin-run">Run</button>';
    const model = host.model ? host.model.namespace + ':' + host.model.version + '/' + host.model.fileName : '-';
    this.querySelector('[data-testid="e2e-plugin-info"]').textContent =
      [host.apiVersion, host.pluginId, host.commandId, host.kind, host.language, model, host.selectedElement || '-'].join('|');
    this.querySelector('[data-testid="e2e-plugin-run"]').addEventListener('click', async () => {
      if (host.kind === 'generate') {
        const result = await host.backend.generate('e2e', {uppercase: 'true'});
        for (const file of result.files) await host.saveFile(file);
        host.notify('Generated by plugin', 'success');
      } else {
        const result = await host.backend.importModel('e2e', new File(['{}'], 'model.json'), {namespace: 'org.eclipse.examples.plugin'});
        await host.workspace.openModel(result.models[0]);
        host.notify('Imported by plugin', 'success');
      }
      host.close();
    });
  }
}
if (!customElements.get('${MOCK_PLUGIN_ELEMENT}')) customElements.define('${MOCK_PLUGIN_ELEMENT}', E2eElement);
`;

/** The content of the file the mocked generator creates. */
export const MOCK_GENERATED_CONTENT = 'generated by e2e';

export interface MockPluginCommand {
  id: string;
  kind: 'import' | 'generate';
  label: string | null;
  labels: Record<string, string>;
  icon: string;
  placements: ('menu' | 'toolbar')[];
  menu: string;
}

export interface MockPlugin {
  id: string;
  name: string;
  version: string;
  description: string | null;
  state: 'ACTIVE' | 'FAILED' | 'INACTIVE' | 'DISABLED' | 'PENDING';
  enabled: boolean;
  restartRequired: boolean;
  error: string | null;
  frontend: {entry: string; element: string} | null;
  commands: MockPluginCommand[];
  actions: string[];
  importers: string[];
  generators: string[];
}

export function mockPlugin(overrides: Partial<MockPlugin> = {}): MockPlugin {
  return {
    id: 'e2e-import',
    name: 'E2E Import',
    version: '1.0.0',
    description: 'Imports models in end-to-end tests.',
    state: 'ACTIVE',
    enabled: true,
    restartRequired: false,
    error: null,
    frontend: {entry: 'frontend/main.js', element: MOCK_PLUGIN_ELEMENT},
    commands: [
      {
        id: 'import',
        kind: 'import',
        label: 'Import from E2E...',
        labels: {de: 'Aus E2E importieren...'},
        icon: 'file_download',
        placements: ['menu'],
        menu: 'file/import',
      },
      {
        id: 'export',
        kind: 'generate',
        label: 'Export to E2E...',
        labels: {de: 'Nach E2E exportieren...'},
        icon: 'file_upload',
        placements: ['menu', 'toolbar'],
        menu: 'generate',
      },
    ],
    actions: [],
    importers: ['e2e'],
    generators: ['e2e'],
    ...overrides,
  };
}

/** The requests the mocked plugin backend received, e.g. to assert uploads. */
export interface PluginBackendMock {
  plugins: MockPlugin[];
  requests: {method: string; path: string}[];
  /** Turns plugins waiting for a restart into running ones, as a restarted backend would. */
  restart(): void;
}

/**
 * Mocks the plugin endpoints of the backend with an in-memory plugin list. Installed plugins wait for a restart of the
 * backend, like in the real application.
 */
export async function mockPluginBackend(page: Page, plugins: MockPlugin[] = []): Promise<PluginBackendMock> {
  const backend: PluginBackendMock = {
    plugins: [...plugins],
    requests: [],
    restart() {
      backend.plugins = backend.plugins
        .filter(plugin => plugin.state !== 'PENDING' || plugin.enabled)
        .map(plugin => ({...plugin, restartRequired: false, state: plugin.enabled ? 'ACTIVE' : 'DISABLED'}));
    },
  };

  const overview = () => ({
    pluginApiVersion: 1,
    plugins: backend.plugins,
    restartRequired: backend.plugins.some(plugin => plugin.restartRequired),
  });
  const json = (route: Route, body: unknown, status = 200) =>
    route.fulfill({status, contentType: 'application/json', body: JSON.stringify(body)});

  await page.route(/\/ame\/api\/plugins(\/.*)?(\?.*)?$/, async route => {
    const request = route.request();
    const path = new URL(request.url()).pathname.replace(/^.*\/ame\/api\/plugins/, '');
    const method = request.method();
    backend.requests.push({method, path});
    const [, id, resource, ...rest] = path.split('/');

    if (method === 'GET' && !id) return json(route, overview());

    if (method === 'POST' && !id) {
      const installed = mockPlugin({state: 'PENDING', restartRequired: true});
      backend.plugins = [...backend.plugins.filter(plugin => plugin.id !== installed.id), installed];
      return json(route, installed, 201);
    }

    const plugin = backend.plugins.find(candidate => candidate.id === id);
    if (!plugin) return json(route, {error: {message: `The plugin "${id}" is not installed.`}}, 404);

    if (method === 'DELETE' && !resource) {
      backend.plugins = backend.plugins.filter(candidate => candidate !== plugin);
      return json(route, overview());
    }

    if (method === 'PUT' && resource === 'enabled') {
      const {enabled} = request.postDataJSON();
      Object.assign(plugin, {enabled, restartRequired: enabled !== (plugin.state === 'ACTIVE')});
      return json(route, plugin);
    }

    if (method === 'GET' && resource === 'frontend' && rest.join('/') === 'main.js') {
      return route.fulfill({status: 200, contentType: 'text/javascript', body: MOCK_PLUGIN_MODULE});
    }

    if (method === 'POST' && resource === 'importers') {
      return json(route, {
        models: [{namespace: 'org.eclipse.examples.plugin', version: '1.0.0', fileName: 'PluginAspect.ttl', content: MOCK_PLUGIN_MODEL}],
        warnings: [],
      });
    }

    if (method === 'POST' && resource === 'generators') {
      const {model} = request.postDataJSON();
      if (!model?.content) return json(route, {error: {message: 'No model'}}, 400);
      return json(route, {
        files: [{fileName: 'model.e2e.txt', mediaType: 'text/plain', content: Buffer.from(MOCK_GENERATED_CONTENT).toString('base64')}],
        warnings: [],
      });
    }

    return json(route, {error: {message: `Unexpected request ${method} ${path}`}}, 400);
  });

  return backend;
}
